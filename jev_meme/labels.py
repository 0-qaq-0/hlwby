"""八艺 —— 八个字（典孝急乐蚌批赢麻）的判定标准。

每个词条包含两部分：
  * ``description`` —— 交给 Jev/SemIf 引擎的选项描述，模型直接读它的 logits。
    **这段文本就是这套系统的全部「训练」**：描述在推理时才读进去，不写进权重。
  * ``hint`` —— 只给页面展示用的人话解释。

判定依据是「对方做了什么 / 我处于什么处境」，八个词：

    典 —— 对方在陈述观点、分析原因
    孝 —— 对方在维护、吹捧一个你不支持的人或事
    急 —— 对方在辩论、分点论述、逐条回击
    乐 —— 对方术语堆砌、故弄玄虚，你看不懂
    蚌 —— 对方把球踢给你，要你表态、拿方案
    批 —— 对方一刀切地批判、扣帽子
    赢 —— 自己说了一句自认为一针见血的金句
    麻 —— 反驳不了也不想争了，敷衍一句认输

写锚点的实测结论（见 docs/EVAL.md）：

  1. **描述「文本长什么样」，不是「说话人在干什么」。** 这条最重要 ——
     这套定义是关系式的（「当对方辩论时」），照字面写锚点会全军覆没，
     全部塌缩到「赢」。改成「逐条辩论、分点回击，常见开头是『第一……第二……』」
     之后，准确率从 50% 跳到 96%。
  2. **给例句，别写抽象定义。**
  3. **要示范，不要解释。** 试过加「区别：这不是 X」式元说明，反而更差 ——
     描述里提到别的词名会把概率漏给那些词。
  4. **别为了长度好看去删例句。** 各词描述长度均衡只是次要因素。
  5. **页面示例要挑该词的典型样本**，边界样本会让系统看起来像坏的。
"""

